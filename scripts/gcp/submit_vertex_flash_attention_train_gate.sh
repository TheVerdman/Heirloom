: "${HEIRLOOM_CUDA_FIXTURE_PRECISION:=amp-bf16}"
: "${HEIRLOOM_CUDA_FIXTURE_BATCH_SIZE:=4}"
: "${HEIRLOOM_CUDA_FIXTURE_BLOCK_SIZE:=512}"
