: "${HEIRLOOM_EXPECT_FLASH_BF16_ATTENTION:=1}"
: "${HEIRLOOM_REQUIRE_TENSOR_CORES:=1}"
: "${HEIRLOOM_EXPECT_TENSOR_CORES:=1}"
: "${HEIRLOOM_EXPECT_ATTENTION_TENSOR_CORES:=1}"

export HEIRLOOM_VERTEX_VALIDATE_MODE
export HEIRLOOM_VERTEX_ACCELERATOR_TYPE
export HEIRLOOM_VERTEX_ACCELERATOR_COUNT
export HEIRLOOM_RUN_QUICK_CLIPPY
export HEIRLOOM_RUN_CUDA_STORAGE_TESTS
export HEIRLOOM_RUN_TENSOR_CORE_MICROBENCH
export HEIRLOOM_GPU_SMOKE_DEVICES
export HEIRLOOM_RUN_NCCL_PROBE
export HEIRLOOM_NCCL_PROBE_DEVICES
