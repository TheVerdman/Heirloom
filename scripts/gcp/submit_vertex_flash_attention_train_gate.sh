: "${HEIRLOOM_CUDA_FLASH_BF16_ATTENTION_TENSOR_CORE:=1}"
: "${HEIRLOOM_CUDA_FLASH_BF16_ATTENTION_BACKWARD:=1}"
: "${HEIRLOOM_CUDA_FLASH_BF16_ATTENTION_TIMING:=1}"
