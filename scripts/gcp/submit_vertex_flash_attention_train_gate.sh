export HEIRLOOM_CUDA_FIXTURE_DISTRIBUTED
export HEIRLOOM_CUDA_FIXTURE_PRECISION
export HEIRLOOM_CUDA_FIXTURE_BATCH_SIZE
export HEIRLOOM_CUDA_FIXTURE_BLOCK_SIZE
export HEIRLOOM_CUDA_FIXTURE_D_MODEL
export HEIRLOOM_CUDA_FIXTURE_N_HEADS
export HEIRLOOM_CUDA_FIXTURE_FF_HIDDEN
